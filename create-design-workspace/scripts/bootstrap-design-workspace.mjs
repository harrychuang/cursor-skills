import { access, cp, mkdir, readdir, readFile, stat, writeFile } from 'node:fs/promises'
import { constants } from 'node:fs'
import path from 'node:path'
import { execFile } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import { promisify } from 'node:util'

const execFileAsync = promisify(execFile)

const __filename = fileURLToPath(import.meta.url)
const __dirname = path.dirname(__filename)
const skillRoot = path.dirname(__dirname)
const templateDir = path.join(skillRoot, 'assets', 'template')

function readFlag(name) {
  const args = process.argv.slice(2)
  const idx = args.indexOf(name)
  return idx >= 0 ? args[idx + 1] : undefined
}

function readMultiFlag(name) {
  const args = process.argv.slice(2)
  const values = []
  for (let i = 0; i < args.length; i += 1) {
    if (args[i] === name && args[i + 1]) values.push(args[i + 1])
  }
  return values
}

function hasFlag(name) {
  return process.argv.slice(2).includes(name)
}

function parseFigmaUrl(input) {
  const url = new URL(input)
  if (url.hostname !== 'www.figma.com') {
    throw new Error('Only https://www.figma.com/design/... URLs are supported')
  }
  if (!url.pathname.startsWith('/design/')) {
    throw new Error('Only /design/ URLs are supported')
  }
  if (url.pathname.includes('/branch/')) {
    throw new Error('Branch URLs are not supported')
  }
  const parts = url.pathname.split('/').filter(Boolean)
  if (parts.length < 2) {
    throw new Error('Missing Figma file key')
  }
  const nodeIdRaw = url.searchParams.get('node-id')
  if (!nodeIdRaw) {
    throw new Error('Missing node-id query parameter')
  }
  return {
    fileKey: parts[1],
    nodeId: nodeIdRaw.replace(/-/g, ':')
  }
}

async function ensureReadableFile(filePath) {
  await access(filePath, constants.R_OK)
  const fileStat = await stat(filePath)
  if (!fileStat.isFile()) {
    throw new Error(`Screenshot path is not a file: ${filePath}`)
  }
}

async function ensureSafeTarget(targetDir, force) {
  try {
    const targetStat = await stat(targetDir)
    if (!targetStat.isDirectory()) {
      throw new Error(`Target exists and is not a directory: ${targetDir}`)
    }
    const entries = await readdir(targetDir)
    if (entries.length > 0 && !force) {
      throw new Error(`Target directory is not empty: ${targetDir}. Re-run with --force or choose an empty directory.`)
    }
  } catch (error) {
    if (error && error.code === 'ENOENT') {
      await mkdir(targetDir, { recursive: true })
      return
    }
    throw error
  }
}

async function copyTemplateContents(targetDir, force) {
  const entries = await readdir(templateDir)
  for (const entry of entries) {
    await cp(path.join(templateDir, entry), path.join(targetDir, entry), {
      recursive: true,
      force
    })
  }
}

async function setProjectName(targetDir, projectName) {
  if (!projectName) return
  const configPath = path.join(targetDir, 'workspace.config.json')
  const config = JSON.parse(await readFile(configPath, 'utf8'))
  config.projectName = projectName
  await writeFile(configPath, JSON.stringify(config, null, 2) + '\n', 'utf8')
}

async function configureFigma(targetDir, figmaUrl, figmaPat, figmaAuthMode) {
  if (!figmaUrl) return null
  const parsed = parseFigmaUrl(figmaUrl)
  const envPath = path.join(targetDir, '.env.local')
  const lines = [
    '# Generated by create-design-workspace bootstrap',
    '# Use FIGMA_PAT, or set FIGMA_AUTH_MODE=connector when your tool already has authenticated Figma MCP/connector access.',
    `FIGMA_FILE_URL=${figmaUrl}`,
    `FIGMA_NODE_ID=${parsed.nodeId}`,
    `FIGMA_PAT=${figmaPat ?? ''}`,
    `FIGMA_AUTH_MODE=${figmaAuthMode ?? ''}`
  ]
  await writeFile(envPath, lines.join('\n') + '\n', 'utf8')
  return parsed
}

async function copyScreenshots(targetDir, screenshotPaths) {
  const copied = []
  for (const screenshotPath of screenshotPaths) {
    const absolutePath = path.resolve(screenshotPath)
    await ensureReadableFile(absolutePath)
    const targetPath = path.join(targetDir, 'reference', path.basename(absolutePath))
    await cp(absolutePath, targetPath, { force: true })
    copied.push(targetPath)
  }
  return copied
}

async function runWorkspaceSync(targetDir) {
  await execFileAsync(process.execPath, [path.join(targetDir, 'scripts', 'sync-workspace.mjs')], {
    cwd: targetDir
  })
}

const targetDir = path.resolve(readFlag('--target') ?? process.cwd())
const projectName = readFlag('--project-name')
const figmaUrl = readFlag('--figma-url')
const figmaPat = readFlag('--figma-pat') ?? ''
const figmaAuthMode = readFlag('--figma-auth-mode') ?? ''
const screenshotPaths = readMultiFlag('--screenshot')
const force = hasFlag('--force')

await ensureSafeTarget(targetDir, force)
await copyTemplateContents(targetDir, force)
await setProjectName(targetDir, projectName)
const figmaConfig = await configureFigma(targetDir, figmaUrl, figmaPat, figmaAuthMode)
const copiedScreenshots = await copyScreenshots(targetDir, screenshotPaths)
await runWorkspaceSync(targetDir)

console.log(`Bootstrapped design workspace in ${targetDir}`)
if (projectName) console.log(`- projectName: ${projectName}`)
if (figmaConfig) {
  console.log(`- figma fileKey: ${figmaConfig.fileKey}`)
  console.log(`- figma nodeId: ${figmaConfig.nodeId}`)
  if (!figmaPat && figmaAuthMode !== 'connector') {
    console.log('- warning: FIGMA_PAT is empty and FIGMA_AUTH_MODE is not connector; add FIGMA_PAT or set FIGMA_AUTH_MODE=connector before Figma-first automation or Phase 0')
  }
}
if (copiedScreenshots.length > 0) {
  console.log(`- copied ${copiedScreenshots.length} screenshot(s) into reference/`)
}
console.log('- next: run `npm run workspace:init` inside the target directory')
console.log('- then run `npm run workspace:check` and continue from start-here/KICKSTART.md')
